const { chromium } = require('playwright');
const SH = require('path').join(__dirname, 'shots/'); require('fs').mkdirSync(SH, { recursive: true });
(async () => {
  const b = await chromium.launch();
  const page = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage(); page.setDefaultTimeout(8000); const T0 = Date.now(); const lg = console.log; console.log = (...a) => lg(((Date.now() - T0) / 1000).toFixed(1) + 's', ...a);
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error' && !/Failed to load/.test(m.text())) errors.push(m.text()); });
  await page.goto('http://localhost:5173/');
  await page.click('[data-action=guest]');
  await page.waitForSelector('.snake-card');
  await page.screenshot({ path: SH + '50-home-snake.png' });
  await page.click('.hero');
  await page.waitForSelector('.dialogue');
  console.log('home npc:', await page.$eval('.dialogue', (e) => e.innerText.replace(/\n/g, ' ')));
  await page.click('.snake-card');
  await page.waitForSelector('[data-action=start]');
  await page.screenshot({ path: SH + '51-snake-menu.png' });
  await page.click('[data-action=level][data-v=hard]');
  await page.click('[data-action=start]');
  await page.waitForSelector('#cv');
  await page.waitForTimeout(300);
  console.log('start dialogue:', await page.$eval('.dialogue', (e) => e.innerText.replace(/\n/g, ' ')).catch(() => 'none'));
  // steer toward food with simple AI using the engine state through keyboard
  await page.screenshot({ path: SH + '52a-countdown.png' });
  await page.waitForTimeout(1800);
  await page.keyboard.press('ArrowUp');
  await page.waitForTimeout(150);
  await page.screenshot({ path: SH + '52-snake-play.png' });
  if (!(await page.$('.result-overlay'))) await page.click('.game-top [data-action=pause]');
  await page.waitForTimeout(300);
  console.log('paused visible:', await page.$eval('#pz', (e) => !e.classList.contains('hidden')).catch(() => 'n/a (already over)'));
  if (!(await page.$('.result-overlay'))) await page.click('#pz [data-action=pause]');
  await page.waitForSelector('.result-overlay', { timeout: 30000 });
  await page.waitForTimeout(1300);
  await page.screenshot({ path: SH + '53-snake-over.png' });
  console.log('result:', await page.$eval('.result-box', (e) => e.innerText.replace(/\n+/g, ' | ')));
  console.log('dialogue:', await page.$eval('.dialogue', (e) => e.innerText.replace(/\n/g, ' ')).catch(() => 'none'));
  console.log('stats:', JSON.stringify(await page.evaluate(() => import('./js/core/store.js').then((m) => m.store.get().stats.snake))));
  await page.click('.result-overlay [data-i="0"]');
  await page.waitForTimeout(500);
  console.log('restarted:', !!(await page.$('#cv')));
  // sound studio dialogues tab
  page.evaluate(() => import('./js/core/router.js').then((m) => { m.go('sound-studio'); }));
  await page.waitForSelector('.modal .btn.primary');
  console.log('quit confirm:', await page.$eval('.modal', (e) => e.innerText.split('\n')[0]));
  await page.click('.modal .btn.primary');
  await page.waitForSelector('[data-action=tab][data-v=dialogues]');
  await page.click('[data-action=tab][data-v=dialogues]');
  await page.click('[data-action=line][data-cat=boss][data-i="3"]');
  await page.waitForTimeout(200);
  console.log('preview:', await page.$eval('.dialogue', (e) => e.innerText.replace(/\n/g, ' ')));
  console.log('lines listed:', await page.$$eval('[data-action=line]', (x) => x.length));
  await page.screenshot({ path: SH + '54-dialogues-tab.png' });
  // map snake location
  await page.evaluate(() => import('./js/core/router.js').then((m) => m.go('map')));
  await page.waitForTimeout(1200);
  await page.click('[data-loc=snake]', { force: true });
  await page.waitForTimeout(900);
  console.log('map card:', await page.$eval('.map-card', (e) => e.innerText.slice(0, 40).replace(/\n/g, ' ')));
  await page.screenshot({ path: SH + '55-map-snake.png' });
  console.log('ERRORS', errors);
  await b.close();
})();
